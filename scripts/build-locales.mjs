import { readdir, readFile, writeFile } from 'node:fs/promises';
import english from '../src/locales/en.mjs';
import { validateCatalog } from '../src/locales/catalog-validation.mjs';

const check = process.argv.includes('--check'), strict = process.argv.includes('--strict');
const packs = [], errors = [], ids = new Set(), aliases = new Set();
for (const file of (await readdir('src/locales/packs')).filter(file => file.endsWith('.json')).sort()) {
  const pack = JSON.parse(await readFile(`src/locales/packs/${file}`, 'utf8'));
  const report = validateCatalog(pack, english);
  if (file !== `${pack.locale.id}.json` || ids.has(pack.locale.id)) errors.push(`${file}: duplicate or mismatched ID`);
  ids.add(pack.locale.id);
  for (const alias of pack.locale.aliases ?? []) {
    if (aliases.has(alias)) errors.push(`${file}: duplicate alias ${alias}`);
    aliases.add(alias);
  }
  errors.push(...report.errors.map(error => `${file}: ${error}`));
  for (const item of report.incompletePlurals) {
    const warning = `${file}: ${item.key} lacks ${item.forms.join(', ')}; those forms use English fallback`;
    if (strict) errors.push(warning); else console.warn(warning);
  }
  if (strict && pack.locale.id !== 'en' && report.missing.length) errors.push(`${file}: ${report.missing.length} untranslated messages`);
  console.log(`${pack.locale.id}: ${pack.locale.id === 'en' ? Object.keys(english).length : Object.keys(pack.messages).length}/${Object.keys(english).length} messages; ${pack.locale.id === 'en' ? 0 : report.missing.length} use English fallback`);
  packs.push(pack);
}
for (const alias of aliases) if (ids.has(alias)) errors.push(`Alias ${alias} shadows a locale ID`);
if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1; }
else {
  const data = `// Generated by npm run locales:build. Edit packs/*.json, then regenerate.\nconst packs = ${JSON.stringify(packs, null, 2)};\nfor (const pack of packs) {\n  for (const message of Object.values(pack.messages)) if (typeof message === 'object') Object.freeze(message);\n  Object.freeze(pack.messages);\n  if (pack.locale.aliases) Object.freeze(pack.locale.aliases);\n  Object.freeze(pack.locale); Object.freeze(pack);\n}\nexport default Object.freeze(packs);\n`;
  const target = 'src/locales/locale-packs.mjs';
  if (check) { if (await readFile(target, 'utf8').catch(() => '') !== data) { console.error('Generated locale registry is stale. Run npm run locales:build.'); process.exitCode = 1; } }
  else await writeFile(target, data);
}
