/** Promote the approved native Blue study to a synchronous startup asset.
 * Run from the repository root. No geometry construction runs during startup. */
import {readFile,writeFile} from 'node:fs/promises';
import {decodeDocument} from '../src/native-container.mjs';
import {emptyDocument,createFrame,createObject} from '../src/demo.mjs';
import {Editor} from '../src/editor.mjs';

const source=new URL('../design/mascot/pivot-style-2026-09-28/figures/02-blue.stkz',import.meta.url);
const {document}=await decodeDocument(new Uint8Array(await readFile(source)),'stkz');
const figure=document.figure_types[0];figure.name='Blue';
const report=emptyDocument();report.figure_types=[figure];
report.keyframes=[createFrame([createObject(figure,1,480,280)])];
const editor=new Editor({demo:false});editor.load(report);
for(const name of ['Left forearm','Right forearm','Left lower leg','Right lower leg']){
  editor.select(1,figure.segments.findIndex(s=>s.name===name));
  editor.setNodeIK({enabled:true,pinned:false,chainLength:2,bendDirection:0});
}
const asset={figure:editor.figure,object:editor.serialize().keyframes[0].objects[0]};
await writeFile(new URL('../src/startup-blue-data.mjs',import.meta.url),
  '// Generated by scripts/build-startup-blue.mjs from the approved Blue native figure.\n'+
  '// A fresh literal keeps each new document independent; mesh construction is offline.\n'+
  `export function createBlueStartupPose(){return ${JSON.stringify(asset)};}\n`);
console.log(`Blue startup asset: ${figure.segments.length} joints, ${figure._styk.spatialMesh.indices.length/3} triangles.`);
